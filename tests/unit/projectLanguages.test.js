import { readFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

import { projectsData } from '@/app/data';
import { pruneEmpty } from '@/components/seo/JsonLd';
import { allProjectLanguages, languagesFor } from '@/lib/seo/projectLanguages';
import { projectPage } from '@/lib/seo/schema';

// ── Why this file exists ────────────────────────────────────────────────────
// `programmingLanguage` was omitted from the project schema on the grounds that
// the only source needed a token and a network call inside `next build`
// (docs/seo.md §12). The committed map restores the property WITHOUT
// reintroducing either, and the whole value of that trade rests on two
// properties a reader cannot check by eye:
//
//   1. The published claim is withheld, not guessed, wherever the data is
//      absent — a private repo, an empty repo, or a project added since the
//      last refresh.
//   2. The file cannot grow claims about projects the site no longer shows.
//
// Both are asserted here against the REAL committed file, not a fixture: the
// point is that the artifact shipping to production is correct, and a fixture
// would pass happily while the committed file said something else.

const raw = JSON.parse(
  readFileSync(new URL('../../src/data/project-languages.json', import.meta.url), 'utf8'),
);

const publicProjects = projectsData.filter((project) => !project.private);
const privateProjects = projectsData.filter((project) => project.private);

describe('the committed language map', () => {
  it('carries the generated-file warning, so nobody hand-edits it', () => {
    // The script overwrites this file wholesale. A hand-edit would be lost on
    // the next refresh with no warning, so the banner is the only thing
    // standing between a contributor and silently discarded work.
    expect(raw.$comment).toMatch(/GENERATED by scripts\/refresh-project-languages\.mjs/);
  });

  it('holds no entry for a private repository', () => {
    // Matching `codeRepository`, which is withheld for private projects rather
    // than pointing at a URL that answers 404 to every reader. A language
    // breakdown nobody can open is the same kind of unverifiable claim.
    for (const project of privateProjects) {
      expect(allProjectLanguages()).not.toHaveProperty(project.repo);
    }
  });

  it('holds no entry for a repository that is not in projectsData', () => {
    // The prune half of the refresh script. Without it the file accumulates
    // languages for projects that have been removed from the site — claims
    // that are published by nothing but would mislead the next reader of the
    // file into thinking the project still exists.
    const known = new Set(publicProjects.map((project) => project.repo));
    for (const repo of Object.keys(allProjectLanguages())) {
      expect(known).toContain(repo);
    }
  });

  it('lists languages as a non-empty array of strings', () => {
    for (const [repo, languages] of Object.entries(allProjectLanguages())) {
      expect(Array.isArray(languages), `${repo} must map to an array`).toBe(true);
      expect(languages.length, `${repo} must not be an empty array`).toBeGreaterThan(0);
      for (const language of languages) {
        expect(typeof language).toBe('string');
        expect(language.trim()).not.toBe('');
      }
    }
  });
});

describe('languagesFor', () => {
  it('withholds rather than guesses for a private project', () => {
    for (const project of privateProjects) {
      expect(languagesFor(project)).toBeUndefined();
    }
  });

  it('returns undefined — never [] — for an unknown repository', () => {
    // The distinction matters at the far end: `projectPage` prunes undefined
    // away, but would serialise an empty array as `"programmingLanguage": []`,
    // which positively asserts that the repository contains no code. Every
    // case reaching here is "unknown", not "none".
    expect(languagesFor({ repo: 'MA1002643/does-not-exist' })).toBeUndefined();
    expect(languagesFor({})).toBeUndefined();
    expect(languagesFor(undefined)).toBeUndefined();
  });

  it('returns the recorded list for a project that has one', () => {
    const [repo, expected] = Object.entries(allProjectLanguages())[0];
    const project = publicProjects.find((candidate) => candidate.repo === repo);
    expect(languagesFor(project)).toEqual(expected);
  });
});

describe('the property as published', () => {
  it('reaches the SoftwareSourceCode node for a project with languages', () => {
    const [repo] = Object.entries(allProjectLanguages())[0];
    const project = publicProjects.find((candidate) => candidate.repo === repo);

    const node = projectPage(project, {
      programmingLanguage: languagesFor(project),
    })['@graph'].find((entry) => entry['@type'] === 'SoftwareSourceCode');

    expect(node.programmingLanguage).toEqual(allProjectLanguages()[repo]);
  });

  it('is absent entirely — not null, not [] — for a private project', () => {
    const project = privateProjects[0];

    // Asserted against the PUBLISHED shape, not the builder's return value.
    // `projectPage` legitimately hands back `programmingLanguage: undefined`;
    // the key is dropped by `pruneEmpty` in JsonLd.jsx on the way to the page,
    // which is the same boundary `codeRepository` is withheld at. Asserting on
    // the intermediate object would fail on correct behaviour — a key set to
    // undefined still satisfies `toHaveProperty` — and, worse, would pass if
    // someone changed the builder to emit `null`, which is the error Google's
    // Rich Results Test actually reports.
    const published = pruneEmpty(
      projectPage(project, { programmingLanguage: languagesFor(project) }),
    );
    const node = published['@graph'].find(
      (entry) => entry['@type'] === 'SoftwareSourceCode',
    );

    expect(node).not.toHaveProperty('programmingLanguage');
    // The sibling withholding, asserted in the same place so the two cannot
    // drift apart: a private project publishes neither the repository URL nor
    // its languages.
    expect(node).not.toHaveProperty('codeRepository');
    // …and the node still exists, so the case above is testing a real published
    // document rather than passing vacuously on a pruned-away shell.
    expect(node.name).toBe(project.name);
  });
});

describe('refresh staleness', () => {
  it('reports which public projects have no languages recorded', () => {
    // NOT a failure. A project added to data.js since the last refresh is an
    // ordinary intermediate state, and failing the build on it would mean
    // every new project is blocked on someone remembering to run a script —
    // which is exactly the kind of coupling the omission decision was avoiding.
    // The property degrades to absent, which is the pre-existing behaviour.
    //
    // This case exists to make the state VISIBLE rather than silent: the
    // assertion below always passes, and the message names what to run.
    const missing = publicProjects
      .filter((project) => !languagesFor(project))
      .map((project) => project.repo);

    if (missing.length > 0) {
      console.warn(
        `No languages recorded for: ${missing.join(', ')}. ` +
          'Run `node scripts/refresh-project-languages.mjs` and commit the diff. ' +
          '(A repository GitHub reports no languages for — a docs-only or empty ' +
          'one — stays listed here permanently, which is correct.)',
      );
    }

    expect(missing.length).toBeLessThanOrEqual(publicProjects.length);
  });
});
