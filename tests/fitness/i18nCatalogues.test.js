import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';

import { NAMESPACES } from '@/i18n/namespaces';
import { icuSignature } from '../../scripts/i18n-lib.mjs';

// Structural guarantees on the English catalogues (issue #82). The full audit
// across all 19 translated locales is `npm run i18n:audit` (a CI step); these
// are the parts that must hold before any translation exists, so they live
// with the other fitness rules and run with every `npm test`.

const EN = 'messages/en';
const files = readdirSync(EN).filter((f) => f.endsWith('.json'));

describe('English catalogues', () => {
  it('loads every namespace file that exists, and every loaded namespace exists', () => {
    // A file missing from src/i18n/namespaces.js is never loaded, so its
    // strings render as raw keys. A listed namespace with no file is a typo.
    const onDisk = files.map((f) => f.replace(/\.json$/, '')).sort();
    expect([...NAMESPACES].sort()).toEqual(onDisk);
  });

  it.each(files)('%s is valid JSON whose every message parses as ICU', (file) => {
    const json = JSON.parse(readFileSync(join(EN, file), 'utf8'));
    const walk = (node, at) => {
      for (const [k, v] of Object.entries(node)) {
        const here = at ? `${at}.${k}` : k;
        if (v && typeof v === 'object') walk(v, here);
        else {
          expect(typeof v, `${file}:${here}`).toBe('string');
          expect(icuSignature(v).error, `${file}:${here}`).toBeUndefined();
        }
      }
    };
    walk(json, '');
  });

  it('keeps the content catalogues in step with src/app/data.js', () => {
    // Generated by scripts/i18n-data.mjs; editing a project or a role in
    // data.js without regenerating would leave translators working from stale
    // English. `--check` exits non-zero when that has happened.
    expect(() =>
      execFileSync(process.execPath, ['scripts/i18n-data.mjs', '--check'], { stdio: 'pipe' }),
    ).not.toThrow();
  });
});
